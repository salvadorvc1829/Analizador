    private void runActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_runActionPerformed
    DefaultTableModel model = (DefaultTableModel) Ttokens.getModel();
model.setRowCount(0);
    BufferedReader br = new BufferedReader(new StringReader(Ainput.getText()));
    String linea;
    Analizador2_2 A1 = new Analizador2_2();
    StringBuilder salida = new StringBuilder();

    try {
        while ((linea = br.readLine()) != null) {

            if (linea.trim().isEmpty()) continue;
    
            salida.append(A1.VerificarL(linea))
                  .append("\n---------------------\n");
            Aoutput.setText(salida.toString());
            A1.imprimirtable(Ttokens, linea);

        }

        

    } catch (Exception e) {
        Aoutput.setText(e.getMessage());
    }




    }//GEN-LAST:event_runActionPerformed

